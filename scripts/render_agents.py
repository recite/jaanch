"""Render agents/roles/*.md into Claude Code and Codex subagent definitions.

Each agent's instructions are written once. Claude Code wants markdown with
YAML frontmatter in .claude/agents/; Codex wants TOML in .codex/agents/.
Run with --check to fail when the rendered files are stale.
"""

import argparse
import sys
from pathlib import Path

import tomli_w
import yaml

ROOT = Path(__file__).resolve().parent.parent
ROLES_DIR = ROOT / "agents" / "roles"
COMMENT_RULES = ROOT / "agents" / "comment_rules.md"
CLAUDE_DIR = ROOT / ".claude" / "agents"
CODEX_DIR = ROOT / ".codex" / "agents"
# Shipped inside the package so `jaanch instructions <name>` works wherever the
# command is installed. Codex 0.167 rejects custom agent types at spawn time, so
# the skills fall back to a default subagent that reads its role from here.
PACKAGE_DIR = ROOT / "src" / "jaanch" / "agents"
HEADER = (
    "Generated by scripts/render_agents.py from agents/roles/{name}.md. Edit that file, then run make agents."
)


def read_role(path: Path) -> tuple[dict, str]:
    _, frontmatter, body = path.read_text().split("---\n", 2)
    return yaml.safe_load(frontmatter), body.strip()


def instructions(meta: dict, body: str) -> str:
    if meta.get("comment_rules", True):
        body = f"{body}\n\n{COMMENT_RULES.read_text().strip()}"
    return body + "\n"


def render_claude(meta: dict, text: str) -> str:
    frontmatter = {"name": meta["name"], "description": meta["description"]}
    if "claude_tools" in meta:
        frontmatter["tools"] = meta["claude_tools"]
    header = HEADER.format(name=meta["name"])
    return f"---\n{yaml.safe_dump(frontmatter, sort_keys=False)}---\n\n<!-- {header} -->\n\n{text}"


def render_codex(meta: dict, text: str) -> str:
    agent = {"name": meta["name"], "description": meta["description"], "developer_instructions": text}
    return f"# {HEADER.format(name=meta['name'])}\n" + tomli_w.dumps(agent, multiline_strings=True)


def rendered_files() -> dict[Path, str]:
    outputs = {}
    for path in sorted(ROLES_DIR.glob("*.md")):
        meta, body = read_role(path)
        if meta["name"] != path.stem:
            raise ValueError(f"{path}: name {meta['name']!r} must match the file name")
        text = instructions(meta, body)
        outputs[CLAUDE_DIR / f"{path.stem}.md"] = render_claude(meta, text)
        outputs[CODEX_DIR / f"{path.stem}.toml"] = render_codex(meta, text)
        outputs[PACKAGE_DIR / f"{path.stem}.md"] = text
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if rendered files are stale")
    args = parser.parse_args()

    outputs = rendered_files()
    existing = set(CLAUDE_DIR.glob("*.md")) | set(CODEX_DIR.glob("*.toml")) | set(PACKAGE_DIR.glob("*.md"))
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    orphans = sorted(existing - set(outputs))

    if args.check:
        for path in stale + orphans:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale or orphans else 0

    for path in orphans:
        path.unlink()
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"rendered {len(outputs)} files, removed {len(orphans)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
